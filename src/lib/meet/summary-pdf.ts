import "server-only";

import { renderDocumentPdf } from "@/lib/pdf/html-to-pdf-server";

function listHtml(items: unknown, empty = "None recorded"): string {
  const arr = Array.isArray(items) ? items.map(String).filter(Boolean) : [];
  if (!arr.length) return `<p class="muted">${empty}</p>`;
  return `<ul>${arr.map((i) => `<li>${escapeHtml(i)}</li>`).join("")}</ul>`;
}

function asList(items: unknown): string[] {
  return Array.isArray(items) ? items.map(String).map((s) => s.trim()).filter(Boolean) : [];
}

function escapeHtml(s: string) {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

async function meetSummaryToPdfViaJsPdf(summary: {
  title: string;
  summary: string;
  keyPoints?: unknown;
  decisions?: unknown;
  actionItems?: unknown;
  durationSec?: number | null;
  createdAt?: Date | string;
  recordingUrl?: string | null;
}): Promise<Buffer> {
  const { jsPDF } = await import("jspdf");
  const doc = new jsPDF({ unit: "pt", format: "letter" });
  const margin = 48;
  const pageW = doc.internal.pageSize.getWidth();
  const maxW = pageW - margin * 2;
  let y = margin;

  const ensureSpace = (need: number) => {
    if (y + need > doc.internal.pageSize.getHeight() - margin) {
      doc.addPage();
      y = margin;
    }
  };

  const writeBlock = (label: string, body: string, size = 11) => {
    ensureSpace(36);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(10);
    doc.setTextColor(51, 65, 85);
    doc.text(label.toUpperCase(), margin, y);
    y += 16;
    doc.setFont("times", "normal");
    doc.setFontSize(size);
    doc.setTextColor(18, 18, 20);
    const lines = doc.splitTextToSize(body || "—", maxW) as string[];
    for (const line of lines) {
      ensureSpace(16);
      doc.text(line, margin, y);
      y += 14;
    }
    y += 12;
  };

  const writeBullets = (label: string, items: string[]) => {
    ensureSpace(28);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(10);
    doc.setTextColor(51, 65, 85);
    doc.text(label.toUpperCase(), margin, y);
    y += 16;
    doc.setFont("times", "normal");
    doc.setFontSize(11);
    doc.setTextColor(18, 18, 20);
    const list = items.length ? items : ["None recorded"];
    for (const item of list) {
      const lines = doc.splitTextToSize(`• ${item}`, maxW) as string[];
      for (const line of lines) {
        ensureSpace(16);
        doc.text(line, margin, y);
        y += 14;
      }
      y += 4;
    }
    y += 8;
  };

  const duration =
    summary.durationSec != null
      ? `${Math.floor(summary.durationSec / 60)}m ${summary.durationSec % 60}s`
      : "—";
  const when = summary.createdAt ? new Date(summary.createdAt).toLocaleString() : "";

  doc.setFont("helvetica", "bold");
  doc.setFontSize(11);
  doc.setTextColor(194, 65, 12);
  doc.text("STORY TIME MEET · VA SUMMARY", margin, y);
  y += 22;
  doc.setFont("times", "bold");
  doc.setFontSize(20);
  doc.setTextColor(18, 18, 20);
  const titleLines = doc.splitTextToSize(summary.title || "Meet summary", maxW) as string[];
  for (const line of titleLines) {
    ensureSpace(24);
    doc.text(line, margin, y);
    y += 22;
  }
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.setTextColor(100, 116, 139);
  doc.text(`${when} · Duration ${duration}`, margin, y);
  y += 18;
  doc.setDrawColor(249, 115, 22);
  doc.setLineWidth(2);
  doc.line(margin, y, pageW - margin, y);
  y += 20;

  writeBlock("Summary", summary.summary || "");
  writeBullets("Key points", asList(summary.keyPoints));
  writeBullets("Decisions", asList(summary.decisions));
  writeBullets("Action items", asList(summary.actionItems));
  if (summary.recordingUrl) {
    writeBlock(
      "Recording",
      "A recording is available in Story Time Meet → Summaries (in-app player).",
      9,
    );
  }

  ensureSpace(24);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(148, 163, 184);
  doc.text("Generated by Story Time Meet VA", margin, y);

  const arrayBuffer = doc.output("arraybuffer") as ArrayBuffer;
  return Buffer.from(arrayBuffer);
}

export async function meetSummaryToPdfBuffer(summary: {
  title: string;
  summary: string;
  keyPoints?: unknown;
  decisions?: unknown;
  actionItems?: unknown;
  durationSec?: number | null;
  createdAt?: Date | string;
  recordingUrl?: string | null;
}): Promise<Buffer> {
  const duration =
    summary.durationSec != null
      ? `${Math.floor(summary.durationSec / 60)}m ${summary.durationSec % 60}s`
      : "—";
  const when = summary.createdAt ? new Date(summary.createdAt).toLocaleString() : "";

  const bodyHtml = `
    <header class="hero">
      <div class="eyebrow">Story Time Meet · VA summary</div>
      <h1>${escapeHtml(summary.title)}</h1>
      <p class="meta">${escapeHtml(when)} · Duration ${escapeHtml(duration)}</p>
    </header>
    <section>
      <h2>Summary</h2>
      <p class="summary">${escapeHtml(summary.summary)}</p>
    </section>
    <section>
      <h2>Key points</h2>
      ${listHtml(summary.keyPoints)}
    </section>
    <section>
      <h2>Decisions</h2>
      ${listHtml(summary.decisions)}
    </section>
    <section>
      <h2>Action items</h2>
      ${listHtml(summary.actionItems)}
    </section>
    ${
      summary.recordingUrl
        ? `<section><h2>Recording</h2><p class="summary">A recording is available in Story Time Meet → Summaries (in-app player).</p></section>`
        : ""
    }
    <footer class="foot">Generated by Story Time Meet VA</footer>
  `;

  try {
    return await renderDocumentPdf({
      title: `Meet summary — ${summary.title}`,
      bodyHtml,
      extraCss: `
        body {
          font-family: Georgia, "Times New Roman", serif;
          color: #121214;
          padding: 40px 44px;
          line-height: 1.55;
        }
        .hero {
          margin-bottom: 28px;
          padding-bottom: 16px;
          border-bottom: 2px solid #f97316;
        }
        .eyebrow {
          font-family: Arial, sans-serif;
          font-size: 11px;
          letter-spacing: 0.16em;
          text-transform: uppercase;
          color: #c2410c;
        }
        h1 { margin: 10px 0 6px; font-size: 26px; line-height: 1.25; }
        .meta { margin: 0; color: #64748b; font-size: 13px; font-family: Arial, sans-serif; }
        h2 {
          margin: 22px 0 8px;
          font-size: 14px;
          font-family: Arial, sans-serif;
          letter-spacing: 0.08em;
          text-transform: uppercase;
          color: #334155;
        }
        .summary { white-space: pre-wrap; font-size: 14px; }
        ul { padding-left: 18px; margin: 0; }
        li { margin: 6px 0; }
        .muted { color: #94a3b8; font-style: italic; font-size: 13px; }
        .foot {
          margin-top: 36px;
          padding-top: 12px;
          border-top: 1px solid #e2e8f0;
          font-family: Arial, sans-serif;
          font-size: 11px;
          color: #94a3b8;
        }
      `,
    });
  } catch (err) {
    console.warn("[meet-summary-pdf] chromium render failed, using jsPDF fallback", err);
    return meetSummaryToPdfViaJsPdf(summary);
  }
}
